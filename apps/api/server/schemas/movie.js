import { z } from 'zod';

export const ingestMovieSchema = z.object({
  title: z.string().trim().min(1, 'A movie title is required.'),
  originalTitle: z.string().trim().optional().nullable(),
  alternativeTitle: z.string().trim().optional().nullable(),
  releaseYear: z.preprocess((val) => val === '' ? undefined : Number(val), z.number().int().min(0).optional().nullable()),
  releaseDate: z.string().trim().optional().nullable(),
  countryId: z.string().trim().optional().nullable(),
  durationMinutes: z.preprocess((val) => val === '' ? undefined : Number(val), z.number().int().min(0).optional().nullable()),
  synopsis: z.string().trim().optional().nullable(),
  originalLanguageId: z.string().trim().optional().nullable(),
  ageRating: z.string().trim().optional().nullable(),
  personalRating: z.preprocess((val) => val === '' ? undefined : Number(val), z.number().int().min(0).max(10).optional().nullable()),
  favorite: z.boolean().optional(),
  watchedStatus: z.string().trim().optional().nullable().default('unwatched'),
  watchedDate: z.string().trim().optional().nullable(),
  rewatchFlag: z.boolean().optional(),
  notes: z.string().trim().optional().nullable(),
  posterPath: z.string().trim().optional().nullable(),
  imdbId: z.string().trim().optional().nullable(),
  tmdbId: z.string().trim().optional().nullable(),
  imdbUrl: z.string().trim().optional().nullable(),
  tmdbUrl: z.string().trim().optional().nullable(),
  genreIds: z.array(z.string()).optional().default([]),

  formatId: z.string().trim().optional().nullable(),
  editionTypeId: z.string().trim().optional().nullable(),
  movieVersionId: z.string().trim().optional().nullable(),
  distributorId: z.string().trim().optional().nullable(),
  countryEditionId: z.string().trim().optional().nullable(),
  editionYear: z.preprocess((val) => val === '' ? undefined : Number(val), z.number().int().min(0).optional().nullable()),
  region: z.string().trim().optional().nullable(),
  barcode: z.string().trim().optional().nullable(),
  catalogNumber: z.string().trim().optional().nullable(),
  steelbook: z.boolean().optional(),
  slipcover: z.boolean().optional(),
  digibook: z.boolean().optional(),
  booklet: z.boolean().optional(),
  posterIncluded: z.boolean().optional(),
  discCount: z.preprocess((val) => val === '' ? undefined : Number(val), z.number().int().min(0).optional().nullable()),
  condition: z.string().trim().optional().nullable(),
  purchaseDate: z.string().trim().optional().nullable(),
  purchasePrice: z.preprocess((val) => val === '' ? undefined : Number(val), z.number().min(0).optional().nullable()),
  estimatedValue: z.preprocess((val) => val === '' ? undefined : Number(val), z.number().min(0).optional().nullable()),
  locationId: z.string().trim().optional().nullable(),
  collectionId: z.string().trim().optional().nullable(),
  frontCoverPath: z.string().trim().optional().nullable(),
  backCoverPath: z.string().trim().optional().nullable(),
  spineImagePath: z.string().trim().optional().nullable(),
  editionNotes: z.string().trim().optional().nullable(),
});

export const updateMovieSchema = ingestMovieSchema.extend({
  editionId: z.preprocess((val) => Number(val), z.number().int().min(1, 'A valid edition is required.')),
});
